#Find the union and intersection.

set_a = {1, 2, 3, 4}
set_b = {3, 4, 5, 6}

print("Set A:", set_a)
print("Set B:", set_b)

print("Union:", set_a.union(set_b))
print("Intersection:", set_a.intersection(set_b))


#Output:
#Set A: {1, 2, 3, 4}
#Set B: {3, 4, 5, 6}
#Union: {1, 2, 3, 4, 5, 6}
#Intersection: {3, 4}
